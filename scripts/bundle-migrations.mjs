/**
 * Inlines db/migrations/*.sql into a TypeScript module so the API can create
 * its schema inside environments without a filesystem (Vercel functions,
 * container images without the repo tree, etc).
 *
 *   node scripts/bundle-migrations.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const dir = path.resolve('db/migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((file) => ({
  version: file,
  sql: readFileSync(path.join(dir, file), 'utf8'),
}));

const out = path.resolve('server/src/db/migrations.generated.ts');
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(
  out,
  `/** Generated by scripts/bundle-migrations.mjs — do not edit by hand. */\n` +
    `export interface BundledMigration { version: string; sql: string }\n\n` +
    `export const BUNDLED_MIGRATIONS: BundledMigration[] = ${JSON.stringify(entries, null, 2)};\n`,
);
console.log(`Bundled ${entries.length} migration(s) into ${path.relative(process.cwd(), out)}`);
