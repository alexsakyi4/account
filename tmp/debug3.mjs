const { createDb } = await import('../server/src/db/driver.ts');
const { migrate } = await import('../server/src/db/migrate.ts');
const { buildApp } = await import('../server/src/app.ts');
const db = createDb('sqlite:/tmp/dbg3.db');
await migrate(db);
const app = await buildApp({ db, logger: { level: 'error' } });
await app.ready();
const reg = await app.inject({method:'POST',url:'/api/v1/auth/register',payload:{companyName:'Dbg Co',name:'Ann Admin',email:'dbg3@example.com',password:'CorrectHorse123!'}});
const token = reg.json().accessToken;
const H = {authorization:`Bearer ${token}`};
const inv = (m,u,p)=>app.inject({method:m,url:'/api/v1'+u,headers:H,payload:p});
const today = new Date().toISOString().slice(0,10);
const accs = await inv('GET','/accounts');
const income = accs.json().data.find(a=>a.code==='4000').id;
const item = await inv('POST','/items',{sku:'W1',name:'Widget',itemType:'inventory',salesPrice:12000,purchaseCost:7500,incomeAccountId:income,quantityOnHand:0});
const vendor = await inv('POST','/contacts',{name:'Stock Vendor',kind:'vendor'});
const bill = await inv('POST','/bills',{vendorId:vendor.json().id,number:'S1',issueDate:today,status:'open',lines:[{description:'buy',quantity:10,unitPrice:7500,itemId:item.json().id}]});
console.log('bill', bill.statusCode, bill.body.slice(0,200));
const cust = await inv('POST','/contacts',{name:'Stock Customer',kind:'customer'});
const invoice = await inv('POST','/invoices',{contactId:cust.json().id,issueDate:today,status:'sent',lines:[{description:'sell',quantity:3,unitPrice:12000,accountId:income,itemId:item.json().id}]});
console.log('invoice', invoice.statusCode, invoice.body.slice(0,300));
console.log('lines', await db.all('SELECT item_id, quantity FROM invoice_lines'));
console.log('movements', await db.all('SELECT movement_type, quantity, total_cost FROM inventory_movements'));
console.log('cogs entries', await db.all("SELECT je.source_type, je.memo, jl.debit, jl.credit FROM journal_lines jl JOIN journal_entries je ON je.id=jl.entry_id JOIN accounts a ON a.id=jl.account_id WHERE a.system_key='cogs'").catch(e=>e.message));
await app.close();
