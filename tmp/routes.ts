import Fastify from 'fastify';
import { registerRoutes } from '../server/src/routes/index.js';
const app = Fastify({ logger: false });
const list: string[] = [];
app.addHook('onRoute', (r) => { list.push(`${r.method} ${r.url}`); });
await app.register(async (s) => { await registerRoutes(s); }, { prefix: '/api/v1' });
await app.ready();
console.log(list.sort().join('\n'));
console.log('TOTAL', list.length);
await app.close();
